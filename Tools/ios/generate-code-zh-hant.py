def convert_zh_hans_to_zh_hant(text: str) -> str:
    """将简体中文转换为繁体中文（先匹配短语，再替换单字）。"""
    if not text:
        return text

    result = text
    # 1. 替换常用软件/IT短语
    for s_phrase, t_phrase in PHRASE_MAP:
        if s_phrase in result:
            result = result.replace(s_phrase, t_phrase)

    # 2. 逐字查找与转换
    converted_chars = []
    for char in result:
        converted_chars.append(CHAR_S2T.get(char, char))

    return "".join(converted_chars)

def process_catalog(filepath: str):
    """处理单张 .xcstrings 字典文件"""
    print(f"Processing: {os.path.basename(filepath)}")
    with open(filepath, 'r', encoding='utf-8') as f:
        catalog = json.load(f)

    strings_dict = catalog.get("strings", {})
    updated_count = 0

    for key, val in strings_dict.items():
        localizations = val.get("localizations", {})
        if "zh-Hans" in localizations:
            zh_hans_unit = localizations["zh-Hans"].get("stringUnit", {})
            zh_hans_val = zh_hans_unit.get("value", "")

            # 若尚未有 zh-Hant，或更新 zh-Hant
            zh_hant_val = convert_zh_hans_to_zh_hant(zh_hans_val)
            localizations["zh-Hant"] = {
                "stringUnit": {
                    "state": "translated",
                    "value": zh_hant_val
                }
            }
            updated_count += 1

    # 特殊补充：System.xcstrings 中的 language.traditionalChinese
    if os.path.basename(filepath) == "System.xcstrings":
        strings_dict["language.traditionalChinese"] = {
            "extractionState": "manual",
            "localizations": {
                "en": {
                    "stringUnit": {
                        "state": "translated",
                        "value": "Traditional Chinese"
                    }
                },
                "zh-Hans": {
                    "stringUnit": {
                        "state": "translated",
                        "value": "繁体中文"
                    }
                },
                "zh-Hant": {
                    "stringUnit": {
                        "state": "translated",
                        "value": "繁體中文"
                    }
                }
            }
        }

    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f"  ✓ Updated {updated_count} entries for zh-Hant in {os.path.basename(filepath)}")

def main():
    repo_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    catalogs_dir = os.path.join(repo_root, "Sources", "Localization", "Catalogs")
    xcstrings_files = glob.glob(os.path.join(catalogs_dir, "*.xcstrings"))

    if not xcstrings_files:
        print(f"Error: No .xcstrings files found in {catalogs_dir}")
        return

    print(f"Found {len(xcstrings_files)} catalog files.")
    for catalog_file in sorted(xcstrings_files):
        process_catalog(catalog_file)

    print("\nAll catalogs updated with zh-Hant successfully!")

if __name__ == "__main__":
    main()
